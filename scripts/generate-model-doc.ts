// Writes docs/data-model.md from src/model/schema.ts and the generated data,
// so the document and the in-app Data screen can never disagree.
//
//   npm run docs:model
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { RELATIONS, SCHEMA } from '../src/model/schema.ts';
import { loadDataset } from '../tests/load.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const d = loadDataset();
const entity = (key: string): string => key.replace(/[A-Z]/g, (c) => `_${c}`).toUpperCase();
const cell = (s: string): string => s.replace(/\|/g, '\\|');

const er = [
  'erDiagram',
  ...RELATIONS.map(([from, to, label]) => `  ${entity(from)} ||--o{ ${entity(to)} : "${label}"`),
].join('\n');

const tables = SCHEMA.map((t) => {
  const rows = d[t.key];
  const n = Array.isArray(rows) ? rows.length : 1;
  const example = Array.isArray(rows) ? rows[0] : rows;
  return [
    `### ${t.title} \`data/${t.key}.json\``,
    '',
    `${t.desc} ${n} row${n > 1 ? 's' : ''} in the demo.`,
    '',
    '| Field | Type | Meaning |',
    '|---|---|---|',
    ...t.fields.map((f) => `| \`${f.name}\` | ${cell(f.type)} | ${cell(f.desc)} |`),
    '',
    '<details><summary>Example row</summary>',
    '',
    '```json',
    JSON.stringify(example, null, 2),
    '```',
    '',
    '</details>',
  ].join('\n');
}).join('\n\n');

const doc = `# Data model

Generated by \`npm run docs:model\` from \`src/model/schema.ts\`. Do not edit by hand.

TowOps keeps two sides of one business in one dataset, joined by the **truck key** (the normalised plate):

- **Billing**: insurers order missions, each mission carries priced lines, gets an invoice date, then a payment date.
- **Fleet**: what each truck earns and costs per month. Its insurance income is *read from the missions*, never typed twice.

Conventions: dates are \`YYYY-MM-DD\`, months \`YYYY-MM\`, amounts are MAD (Moroccan dirham) with VAT included.

## How the tables connect

\`\`\`mermaid
${er}
\`\`\`

## Rules that hold the model together

1. **One fact per status.** A mission is *invoiced* when it has an \`invoiceDate\`, *paid* when it has a \`paidDate\`, *ready* when every photo slot has a photo. No status column can drift out of step with those facts.
2. **Line totals are stored.** \`rate x roundTrip x quantity\` is computed once and saved, so editing the tariff grid never changes an invoice already sent.
3. **VAT comes out of the price, not on top.** Tariffs are VAT-included; each rate's excl. amount is \`incl / (1 + rate)\`. Foreign insurers are invoiced at 0 %.
4. **A shared tow splits by kilometres.** Extra trucks get the per-km tow line in proportion to the km they drove; truck 1 keeps the rest, so the parts always add up to the mission total.
5. **Fuel is measured full tank to full tank.** L/100 km = litres / (odometer - previous odometer) x 100. A reading that goes backwards is flagged and skipped.
6. **Debts are taken minus paid, per name**, with names matched ignoring case and spacing.

## Tables

${tables}
`;

writeFileSync(join(ROOT, 'docs', 'data-model.md'), doc);
console.log('docs/data-model.md written');
